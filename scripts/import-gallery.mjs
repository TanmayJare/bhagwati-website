import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createCanvas,loadImage} from '@napi-rs/canvas';

// The original collection remains untouched. Both gallery and homepage use these derivatives.
const assetRoot='bhagwati-assets';
const folders=fs.readdirSync(assetRoot);
const fullRoot=path.join(assetRoot,folders.find(f=>!f.includes('sorted')),'bhagwati website');
const selectedRoot=path.join(assetRoot,folders.find(f=>f.includes('sorted')));
const list=root=>fs.readdirSync(root,{recursive:true})
 .filter(f=>/\.(jpe?g|png|webp)$/i.test(f)&&fs.statSync(path.join(root,f)).isFile())
 .sort((a,b)=>a.localeCompare(b,'en',{numeric:true}));
const digest=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const eventNames={
 'gondhal':{en:'Gondhal',mr:'गोंधळ'},'navratri':{en:'Navratri',mr:'नवरात्र'},
 'oct 2022':{en:'October',mr:'ऑक्टोबर'},'may 2023':{en:'May',mr:'मे'},
 'october 2023':{en:'October',mr:'ऑक्टोबर'},'september 2023':{en:'September',mr:'सप्टेंबर'},
 'october':{en:'October',mr:'ऑक्टोबर'},'palkhi':{en:'Palkhi',mr:'पालखी'},
};
// These three originals have sideways pixels without a camera orientation tag.
// All other camera EXIF orientations are handled by the image decoder.
const orientationCorrections=new Set(['2007/DSC04289.JPG','2007/DSC04328.JPG','2007/DSC04330.JPG']);
const previous=new Map((await import('../src/data/gallery.js')).galleryPhotos.map(p=>[p.id,p]));
const photos=[];const byHash=new Map();const counts={};
for(const relative of list(fullRoot)){
 const parts=relative.split(path.sep);const year=Number(parts[0]);
 if(!Number.isInteger(year)||year<2007)throw new Error('Undated image: '+relative);
 const original=path.join(fullRoot,relative);const hash=digest(original);const id=`${year}-${hash.slice(0,12)}`;
 if(byHash.has(hash))throw new Error('Duplicate original photograph: '+relative);
 const destination=`public/images/gallery/${year}`;
 fs.mkdirSync(destination,{recursive:true});
 const correction=orientationCorrections.has(parts.join('/'));
 let image;
 const cached=previous.get(id);
 const ready=cached&&!correction&&fs.existsSync(path.join(destination,`${id}.webp`))&&fs.existsSync(path.join(destination,`${id}-thumb.webp`));
 if(!ready){
  image=await loadImage(original);
  if(correction){const upright=createCanvas(image.height,image.width);const ctx=upright.getContext('2d');ctx.translate(0,image.width);ctx.rotate(-Math.PI/2);ctx.drawImage(image,0,0);image=upright;}
 }
 function encode(max,filename,quality){
  const ratio=Math.min(1,max/Math.max(image.width,image.height));
  const width=Math.round(image.width*ratio),height=Math.round(image.height*ratio);
  const canvas=createCanvas(width,height);canvas.getContext('2d').drawImage(image,0,0,width,height);
  fs.writeFileSync(path.join(destination,filename),canvas.toBuffer('image/webp',quality));
  return {width,height};
 }
 const size=ready?{width:cached.width,height:cached.height}:encode(1920,`${id}.webp`,82);
 if(!ready)encode(640,`${id}-thumb.webp`,76);
 const ordinal=(counts[year]=(counts[year]||0)+1);
 const event=eventNames[parts[1]?.toLowerCase()];
 const mrYear=new Intl.NumberFormat('mr-IN',{useGrouping:false}).format(year);
 const mrOrdinal=new Intl.NumberFormat('mr-IN',{useGrouping:false}).format(ordinal);
 const photo={id,year,src:`/images/gallery/${year}/${id}.webp`,thumbnailSrc:`/images/gallery/${year}/${id}-thumb.webp`,...size,
  title:{en:`${year} · ${event?.en||'Archive'} photograph ${ordinal}`,mr:`${mrYear} · ${event?.mr||'संग्रहातील'} छायाचित्र ${mrOrdinal}`},
  caption:{en:event?`${event.en} ${year}`:`Naleghar · ${year}`,mr:event?`${event.mr} ${mrYear}`:`नळेघर · ${mrYear}`},
  sourceFile:relative.split(path.sep).join('/')};
 photos.push(photo);byHash.set(hash,photo);
 if(photos.length%40===0)console.log(`Prepared ${photos.length} photographs`);
}
const selected=list(selectedRoot).map(relative=>{
 const match=byHash.get(digest(path.join(selectedRoot,relative)));
 if(!match)throw new Error('Selected image missing from master collection: '+relative);
 const year=Number(relative.split(path.sep)[0]);
 if(match.year!==year)throw new Error('Selected image year mismatch: '+relative);
 return match.id;
});
if(new Set(selected).size!==selected.length)throw new Error('Duplicate selected photograph');
fs.writeFileSync('src/data/gallery.js',`// Generated by scripts/import-gallery.mjs from the complete year-wise collection.\nexport const galleryPhotos = ${JSON.stringify(photos,null,2)};\nexport const archiveStartYear = 2007;\n`);
// Retain the chosen homepage display settings when refreshing source assets.
const current=fs.readFileSync('src/data/selectedPhotos.js','utf8');
fs.writeFileSync('src/data/selectedPhotos.js',current.replace(/export const selectedHomepagePhotoIds = \[[\s\S]*?\];/,`export const selectedHomepagePhotoIds = ${JSON.stringify(selected,null,2)};`));
console.log(JSON.stringify({photographs:photos.length,homepageSelections:selected.length,years:counts},null,2));
